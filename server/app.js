import express from 'express';
import { authRouter } from './routes/auth.js';
import { communityInfoRouter } from './routes/community-info.js';
import { dashboardRouter } from './routes/dashboard.js';
import { directoryRouter } from './routes/directory.js';
import { financesRouter } from './routes/finances.js';
import { projectsRouter } from './routes/projects.js';
import { issuesRouter } from './routes/issues.js';
import { listingsRouter } from './routes/listings.js';
import { profileRouter } from './routes/profile.js';
import { pollsRouter } from './routes/polls.js';
import { proposalsRouter } from './routes/proposals.js';
import { propertiesRouter } from './routes/properties.js';
import { streetsRouter } from './routes/streets.js';
import { contractorsRouter } from './routes/contractors.js';
import { decisionsRouter } from './routes/decisions.js';
import { documentsRouter } from './routes/documents.js';
import { announcementsRouter } from './routes/announcements.js';
import { digestsRouter } from './routes/digests.js';
import { notificationsRouter } from './routes/notifications.js';
import { requireMembership } from './middleware/authentication.js';
import { config } from './config.js';

export const app = express();
app.use(express.json());
app.use((request, response, next) => {
  if (request.headers.origin === config.webOrigin) response.setHeader('Access-Control-Allow-Origin', config.webOrigin);
  response.setHeader('Access-Control-Allow-Headers', 'Authorization, Content-Type');
  response.setHeader('Access-Control-Allow-Methods', 'GET, POST, PUT, PATCH, OPTIONS');
  if (request.method === 'OPTIONS') return response.sendStatus(204);
  next();
});
app.get('/api/health', (_request, response) => response.json({ status: 'ok' }));
app.use('/api/auth', authRouter);
app.use('/api/community-info', requireMembership, communityInfoRouter);
app.use('/api/dashboard', requireMembership, dashboardRouter);
app.use('/api/finances', requireMembership, financesRouter);
app.use('/api/projects', requireMembership, projectsRouter);
app.use('/api/issues', requireMembership, issuesRouter);
app.use('/api/decisions', requireMembership, decisionsRouter);
app.use('/api/documents', requireMembership, documentsRouter);
app.use('/api/contractors', requireMembership, contractorsRouter);
app.use('/api/announcements', requireMembership, announcementsRouter);
app.use('/api/notifications', requireMembership, notificationsRouter);
app.use('/api/digests', requireMembership, digestsRouter);
app.use('/api/streets', requireMembership, streetsRouter);
app.use('/api/properties', requireMembership, propertiesRouter);
app.use('/api/profile', requireMembership, profileRouter);
app.use('/api/directory', requireMembership, directoryRouter);
app.use('/api/listings', requireMembership, listingsRouter);
app.use('/api/proposals', requireMembership, proposalsRouter);
app.use('/api/polls', requireMembership, pollsRouter);
app.use((error, _request, response, _next) => { console.error(error); response.status(500).json({ error: 'Внутренняя ошибка сервера.' }); });
